# Somewhere in a Remote House (993201006): Father's Loss (36611). The picture on the mantel; what really happened to
# Mihile's brother. Then Father is gone.
execfile("scripts/quest/_mihile_story.py")

ATAN_NPC = 1541205

if sm.hasQuest(36611):
    try:
        scene_start()
        sm.spawnNpc(ATAN_NPC, -400, 221)
        sm.blind(1, 255, 0, 0)
        sm.sendDelay(300)
        unblack(1000)
        say(ATAN, "Take a look, Mihile.")
        say(ATAN, "You know this picture, of course.")
        me("Of course, it's you and my brother.")
        illust("photo", 1000)
        sm.sendDelay(1000)
        me("It was taken just before the accident...")
        say(ATAN, "It's time you knew exactly what happened.")
        say(ATAN, "All I've told you up until now is that he died in an accident when he was young.")
        say(ATAN, "It was horrible. Too horrible to tell you. I didn't know how.")
        say(ATAN, "But you're older now, and you must want to know. So...")
        say(ATAN, "...The truth is, there was no farming accident. There was a #rmonster#k.")
        say(ATAN, "But wild indeed.")
        say(ATAN, "He was younger than you are now.")
        say(ATAN, "...I had started teaching him the sword, but he was still so small.")
        say(ATAN, "As soon as I heard the screams, I ran to him. But I was too late.")
        say(ATAN, "The monster lay dead beneath him, their blood pooled together.")
        say(ATAN, "All my strength, and I could do nothing for him.")
        illust_off(1000)
        sm.sendDelay(1000)
        me("Father...")
        say(ATAN, "So you understand why I keep you safe.")
        me("I do understand.")
        say(ATAN, "And you're all I have left, you know.")
        say(ATAN, "There's nothing more precious in the world to me. Not even the prospect of bringing back your brother.")
        say(ATAN, "Don't misunderstand me. I love you both.")
        say(ATAN, "But you're alive. I could never gamble with your life for his.")
        say(ATAN, "My sole priority, above all else...")
        say(ATAN, "...is my only child.")
        say(ATAN, "Keep yourself out of danger while I'm gone. And please stay close to home.")
        me("Yes, I will.")
        black(1000)
        finish(36611)
        hide("02")
    finally:
        scene_end()
    caption("Several Days Later")
sm.warpInstanceOut(REMOTE_HOUSE, 0)
sm.dispose()
