execfile("scripts/quest/_mihile_story.py")

if sm.hasQuestCompleted(36601):
    sm.warpInstanceOut(REMOTE_HOUSE, 0)
else:
    try:
        scene_start()
        sm.hideUser(True)
        sm.blind(1, 255, 0, 0)
        sm.sendDelay(1000)
        illust("knight", 1000)
        sm.sendDelay(1000)
        mono("#bThe Knight of Light.#k")
        mono("Possessed of a noble and virtuous soul.", 1)
        mono("When his sword strikes, the ocean splits. When his shield rises, lightning flees.", 1)
        mono("But who could be worthy of such power?", 1)
        mono("Who deserves to carry the #bSoul Shield?#k")
        mono("#bOnly the 'Knight of Light,'#k ordained by the light itself, can make that shield shine.")
        mono("And when its true power awakens...")
        mono("...the shield and the Knight become one, made whole.", 1)
        illust_off(500)
        sm.sendDelay(500)
        illust("teardrop", 500)
        sm.sendDelay(500)
        mono("Upon that shield is a secret, in the form of a mysterious jewel.")
        mono("Called #b'Shinsoo's Teardrop,'#k it holds the collective will of our land's people.")
        mono("Only the #bKnight of Light#k can hold that jewel in his hand.", 1)
        illust_off(1000)
        sm.sendDelay(1000)
        me("(One day, I shall become the #bKnight of Light#k.)")
        me("(With the jewel in my hand, I will make a #bwish#k.)")
        me("(For with that wish...)")
        me("(...my #bbrother#k will return to life, and #bFather's#k heart will heal.)")
        sm.sendDelay(500)
    finally:
        sm.hideUser(False)
        sm.blind(0, 0, 0, 0)
        scene_end()
        sm.warpInstanceOut(LITTLE_ROOM, 0)
sm.dispose()
